"""Reproduce display-only photos and const RGB565 C arrays from licensed originals.

Requires Pillow and pypdf. Run from any directory. Never used by inference.
"""
from pathlib import Path
import hashlib
import json
import struct
from PIL import Image, ImageDraw, ImageFont
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parent
ORIGINALS = ROOT / "originals"
OUTPUT = ROOT / "rgb565_preview"
WIDTH, HEIGHT = 144, 96


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    OUTPUT.mkdir(exist_ok=True)
    # PDF physical page 4 / printed page 475. /Im0 is Figure 2(a), left panel.
    # Its page transform is [195.5499717,0,0,179.7664359,121.14991,516.7943551].
    page = PdfReader(ORIGINALS / "pearl_paper.pdf").pages[3]
    selected = next(im for im in page.images if im.name == "Im0.jp2")
    pearl_source = ORIGINALS / "pearl_page4_Im0.jp2"
    pearl_source.write_bytes(selected.data)
    images = [
        ("millet", "小米", "millet.png", (0, 14, 320, 227)),
        ("pearl", "珍珠粉", "pearl_page4_Im0.jp2", (0, 60, 1087, 785)),
        ("salt", "细盐", "salt.jpg", (0, 400, 3986, 3057)),
        ("sugar", "白砂糖", "sugar.jpg", (0, 96, 2304, 1632)),
    ]
    arrays, report = [], []
    montage = Image.new("RGB", (WIDTH * 2, (HEIGHT + 24) * 2), "#edf2f5")
    draw = ImageDraw.Draw(montage)
    try:
        font = ImageFont.truetype("C:/Windows/Fonts/msyh.ttc", 14)
    except OSError:
        font = ImageFont.load_default()
    for class_id, (key, name, filename, box) in enumerate(images):
        source = ORIGINALS / filename
        image = Image.open(source).convert("RGB").crop(box).resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
        pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in image.getdata()]
        arrays.append(pixels)
        binary = struct.pack("<" + "H" * len(pixels), *pixels)
        (OUTPUT / (key + ".rgb565le")).write_bytes(binary)
        # Preview is decoded from exact packed RGB565 data, not the RGB888 source.
        decoded = Image.new("RGB", (WIDTH, HEIGHT))
        decoded.putdata([(((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31) for v in pixels])
        decoded.save(OUTPUT / (key + ".png"))
        x, y = (class_id % 2) * WIDTH, (class_id // 2) * (HEIGHT + 24)
        montage.paste(decoded, (x, y + 24))
        draw.text((x + 5, y + 2), str(class_id + 1) + " " + name, font=font, fill="#183045")
        report.append(dict(class_id=class_id, result_code=class_id+1, name=name, source=filename,
                           source_sha256=digest(source), source_dimensions=list(Image.open(source).size),
                           crop_ltrb=list(box), output_dimensions=[WIDTH,HEIGHT],
                           bytes=len(binary), rgb565le_sha256=hashlib.sha256(binary).hexdigest()))
    montage.resize((576,480), Image.Resampling.NEAREST).save(ROOT / "four_materials_preview.png")
    folder = ROOT.parent / "stm32/User/particle"
    header = """#ifndef PARTICLE_IMAGES_H
#define PARTICLE_IMAGES_H
#include <stdint.h>
#define PARTICLE_IMAGE_WIDTH 144u
#define PARTICLE_IMAGE_HEIGHT 96u
/* Zero-based model class: millet, pearl powder, fine salt, white sugar. */
extern const uint16_t particle_images[4][PARTICLE_IMAGE_WIDTH * PARTICLE_IMAGE_HEIGHT];
const uint16_t *ParticleImage_Get(uint8_t class_id);
#endif
"""
    (folder / "particle_images.h").write_text(header, encoding="ascii")
    lines = ['/* Generated by assets/generate_images.py. Photo attribution/licenses: assets/SOURCES.md.',
             ' * RGB565: R bits15..11, G bits10..5, B bits4..0. Row-major, no framebuffer.',
             ' * Each image retains its source license. */', '#include "particle_images.h"',
             'const uint16_t particle_images[4][PARTICLE_IMAGE_WIDTH * PARTICLE_IMAGE_HEIGHT] = {']
    for i, pixels in enumerate(arrays):
        lines.append('    { /* class %d */' % i)
        lines += ['        ' + ','.join('0x%04X' % v for v in pixels[j:j+16]) + ',' for j in range(0,len(pixels),16)]
        lines.append('    },')
    lines += ['};', 'const uint16_t *ParticleImage_Get(uint8_t class_id)', '{',
              '    return class_id < 4u ? particle_images[class_id] : (const uint16_t *)0;', '}']
    (folder / "particle_images.c").write_text('\n'.join(lines)+'\n', encoding="ascii")
    (ROOT / "generation_report.json").write_text(json.dumps(dict(total_flash_image_bytes=4*WIDTH*HEIGHT*2,
        source_pdf_sha256=digest(ORIGINALS/'pearl_paper.pdf'), pearl_pdf_page_1based=4,
        pearl_pdf_printed_page=475, pearl_pdf_image_object='Im0 / Figure 2(a)',
        pearl_pdf_transform=[195.5499717,0,0,179.7664359,121.14991,516.7943551], images=report),
        ensure_ascii=False, indent=2)+'\n', encoding="utf-8")
    print("Generated 4 images, 144x96 RGB565, 110592 bytes const data")


if __name__ == "__main__":
    main()
